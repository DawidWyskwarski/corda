package com.example.corda.tuner.data.local.dao

import android.content.Context
import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import androidx.test.ext.junit.runners.AndroidJUnit4
import app.cash.turbine.test
import com.example.corda.tuner.data.local.database.TunerDatabase
import com.example.corda.tuner.data.local.entities.DefaultInstrumentName
import com.example.corda.tuner.data.local.entities.Instrument
import com.google.common.truth.Truth.assertThat
import kotlinx.coroutines.test.runTest
import org.junit.After
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith

@RunWith(AndroidJUnit4::class)
class InstrumentDaoTest {

    private lateinit var db: TunerDatabase
    private lateinit var dao: InstrumentDao

    @Before
    fun setUp() {
        val context = ApplicationProvider.getApplicationContext<Context>()
        db = Room.inMemoryDatabaseBuilder(context, TunerDatabase::class.java)
            .build()
        dao = db.getInstrumentDao()
    }

    @After
    fun tearDown() {
        db.close()
    }

    @Test
    fun insertInstrument_assignsAutogeneratedId_andGetInstrumentsEmitsIt() = runTest {
        val id = dao.insertInstrument(
            Instrument(
                customName = "My Guitar",
                defaultName = DefaultInstrumentName.GUITAR,
                musicNotesCount = 6,
            )
        )

        dao.getInstruments().test {
            val instruments = awaitItem()
            assertThat(instruments).hasSize(1)
            assertThat(instruments[0].id).isEqualTo(id.toInt())
            assertThat(instruments[0].customName).isEqualTo("My Guitar")
            assertThat(instruments[0].defaultName).isEqualTo(DefaultInstrumentName.GUITAR)
            assertThat(instruments[0].musicNotesCount).isEqualTo(6)
            cancelAndIgnoreRemainingEvents()
        }
    }

    @Test
    fun insertInstrument_withExistingId_replacesTheRow() = runTest {
        dao.insertInstrument(
            Instrument(
                id = 1,
                customName = "Original",
                defaultName = DefaultInstrumentName.GUITAR,
                musicNotesCount = 6,
            )
        )
        dao.insertInstrument(
            Instrument(
                id = 1,
                customName = "Replaced",
                defaultName = DefaultInstrumentName.BASS,
                musicNotesCount = 4,
            )
        )

        dao.getInstruments().test {
            val instruments = awaitItem()
            assertThat(instruments).hasSize(1)
            assertThat(instruments[0].id).isEqualTo(1)
            assertThat(instruments[0].customName).isEqualTo("Replaced")
            assertThat(instruments[0].defaultName).isEqualTo(DefaultInstrumentName.BASS)
            assertThat(instruments[0].musicNotesCount).isEqualTo(4)
            cancelAndIgnoreRemainingEvents()
        }
    }

    @Test
    fun updateInstrument_updatesFieldsOfExistingRow() = runTest {
        val id = dao.insertInstrument(
            Instrument(
                customName = "Before",
                defaultName = DefaultInstrumentName.GUITAR,
                musicNotesCount = 6,
            )
        ).toInt()

        dao.updateInstrument(
            Instrument(
                id = id,
                customName = "After",
                defaultName = DefaultInstrumentName.GUITAR,
                musicNotesCount = 7,
            )
        )

        dao.getInstruments().test {
            val instruments = awaitItem()
            assertThat(instruments).hasSize(1)
            assertThat(instruments[0].customName).isEqualTo("After")
            assertThat(instruments[0].musicNotesCount).isEqualTo(7)
            cancelAndIgnoreRemainingEvents()
        }
    }

    @Test
    fun updateInstrument_onNonExistentId_isNoOp() = runTest {
        dao.updateInstrument(
            Instrument(
                id = 999,
                customName = "Ghost",
                defaultName = null,
                musicNotesCount = 6,
            )
        )

        dao.getInstruments().test {
            assertThat(awaitItem()).isEmpty()
            cancelAndIgnoreRemainingEvents()
        }
    }

    @Test
    fun deleteInstrument_removesOnlyTheTargetedRow() = runTest {
        val firstId = dao.insertInstrument(
            Instrument(customName = "Keep", musicNotesCount = 6)
        ).toInt()
        val secondId = dao.insertInstrument(
            Instrument(customName = "Delete", musicNotesCount = 4)
        ).toInt()

        dao.deleteInstrument(secondId)

        dao.getInstruments().test {
            val instruments = awaitItem()
            assertThat(instruments).hasSize(1)
            assertThat(instruments[0].id).isEqualTo(firstId)
            assertThat(instruments[0].customName).isEqualTo("Keep")
            cancelAndIgnoreRemainingEvents()
        }
    }

    @Test
    fun deleteInstrument_withUnknownId_doesNotThrow_andDoesNotAffectExistingRows() = runTest {
        val id = dao.insertInstrument(
            Instrument(customName = "Keep", musicNotesCount = 6)
        ).toInt()

        dao.deleteInstrument(999)

        dao.getInstruments().test {
            val instruments = awaitItem()
            assertThat(instruments).hasSize(1)
            assertThat(instruments[0].id).isEqualTo(id)
            cancelAndIgnoreRemainingEvents()
        }
    }

    @Test
    fun getInstruments_onEmptyDatabase_emitsEmptyList() = runTest {
        dao.getInstruments().test {
            assertThat(awaitItem()).isEmpty()
            cancelAndIgnoreRemainingEvents()
        }
    }
}
